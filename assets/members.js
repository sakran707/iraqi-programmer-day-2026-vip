/** توحيد النص العربي لأغراض المطابقة (تشكيل، ألف/همزة، ياء/ألف مقصورة، تاء مربوطة) */
function normalizeArabicText(s) {
  return String(s || '')
    .replace(/[ً-ْٰـ]/g, '')
    .replace(/[إأآا]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim();
}

/** يبحث عن الأعضاء الذين يطابق اسمهم النص المدخل (بحث جزئي، بحد أدنى حرفين) */
function findMemberMatches(query, limit) {
  const q = normalizeArabicText(query);
  if (q.length < 2) return [];
  const matches = MEMBERS.filter(function (m) {
    return normalizeArabicText(m.name).indexOf(q) !== -1;
  });
  return matches.slice(0, limit || 8);
}
